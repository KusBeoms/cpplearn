// ============================================================
// Step 5 — std::vector (크기가 변하는 배열)
// ============================================================
//
// [지난 스텝 통과 + 참고]
//
//   Step 4 통과. 참조로 받았고, 호출할 때 & 를 안 썼고, 직접 교환했다.
//   요구한 개념을 정확히 썼다.
//
//   참고 세 가지 (통과에는 영향 없음)
//
//   1. void 함수 끝의 return; 은 없어도 된다. 함수가 끝나면 알아서 돌아온다.
//      중간에 빠져나올 때만 쓴다.
//
//   2. std::cout << a << b 는 구분자가 없어서 10 과 -2 가 "10-2" 로 붙는다.
//      << ' ' 같은 걸 사이에 끼우면 읽기 편하다.
//
//   3. 함수 이름을 swap 으로 지은 게 이번엔 통했지만, 위험한 이름이다.
//      C++ 표준 라이브러리에도 std::swap 이 있어서 이름이 겹친다.
//      지금은 우리가 만든 전역 swap 이 먼저 잡혀서 문제가 없었지만,
//      상황에 따라 어느 쪽이 불릴지 헷갈리는 코드가 된다.
//      표준에 있는 이름은 피하는 편이 낫다. (예: swap_values)
//
// ------------------------------------------------------------
//
// [개념] C 의 배열이 C++ 에서는 std::vector 가 된다.
//
//   C 에서 "개수를 미리 모르는 배열" 은 늘 골칫거리였다.
//
//     int arr[100];                        // 넉넉히 잡고 기도하거나
//     int *p = malloc(n * sizeof(int));    // 직접 잡고
//     p = realloc(p, n2 * sizeof(int));    // 모자라면 다시 잡고
//     free(p);                             // 끝나면 반드시 반납
//
//   그리고 배열은 크기를 스스로 모른다. sizeof 로 알아낼 수 있는 건
//   같은 함수 안에서뿐이고, 함수에 넘기는 순간 포인터로 무너져서
//   길이를 따로 같이 넘겨야 했다. func(arr, n) 이 그 이유다.
//
//   std::vector 는 자기 크기를 알고, 필요하면 스스로 늘어나고,
//   끝나면 스스로 메모리를 반납한다. free 를 부를 일이 없다.
//
//     C                                  C++
//     ---------------------------------  --------------------------
//     int a[100];                        std::vector<int> v;
//     malloc / realloc / free            (없음. 알아서 한다)
//     길이를 따로 들고 다녀야 함           v.size()
//     a[i]                               v[i]  (똑같다)
//
// [문법]
//   #include <vector>
//
//   std::vector<int> v;              // 빈 정수 배열
//   std::vector<int> w(5);           // 0 으로 채운 5칸
//   std::vector<int> u = {1, 2, 3};  // 초기값 지정
//
//   v.push_back(10);                 // 뒤에 하나 추가 (크기가 1 늘어난다)
//   v.size()                         // 현재 개수
//   v[0]                             // 접근. 배열과 똑같다.
//   v.empty()                        // 비었는지
//
//   <int> 부분은 "무엇을 담는 배열인지" 다.
//   std::vector<double>, std::vector<std::string> 도 된다.
//
//   전체를 도는 방법은 두 가지다.
//
//     for (int i = 0; i < v.size(); i++)   // C 와 같은 방식
//         std::cout << v[i];
//
//     for (int x : v)                      // 범위 기반 for (C++ 전용)
//         std::cout << x;                  // v 의 원소를 하나씩 x 에 담아준다
//
//   두 번째가 인덱스 실수가 없어서 안전하다. 다만 인덱스 번호가 필요하면
//   첫 번째를 쓴다.
//
// [힌트]
//   - <vector> 헤더를 include 해야 한다.
//   - 개수를 먼저 입력받으므로 몇 개가 올지 미리 알 수 있다.
//     그래도 push_back 으로 하나씩 채워 넣는 방식으로 해볼 것.
//     vector 가 스스로 늘어나는 걸 직접 보는 게 이번 목적이다.
//   - 최댓값은 첫 원소를 후보로 두고 나머지와 비교해 나가면 된다.
//     C 에서 하던 그대로다.
//   - v.size() 는 부호 없는 정수를 돌려준다. int i 와 비교하면
//     -Wall 이 경고를 낼 수 있다. 경고가 떠도 지금은 넘어가도 된다.
//
// ============================================================
// [1차 채점 — 한 줄만 고치면 통과]
//
//   vector, push_back, 범위 기반 for 모두 제대로 썼다. 개념은 다 맞다.
//
//   버그: max 초기값이 -1 이라 음수만 들어오면 틀린다.
//     입력  3 / -5 -3 -9
//     기대  Max = -3
//     실제  Max = -1        ← 배열에 없는 값이 나온다
//
//     "있을 수 없는 작은 값" 으로 초기화하는 접근 자체가 위험하다.
//     최댓값은 반드시 원소 중 하나이므로, 첫 원소를 초기값으로 삼으면 된다.
//
//       int mx = arr[0];
//       for (int x : arr) if (mx < x) mx = x;
//
//   참고 (통과에는 영향 없음)
//     - max 라는 이름은 std::max 와 겹친다. 지난번 swap 과 같은 얘기.
//     - int input; 은 루프 안에서 선언하는 게 낫다. C++ 은 쓰는 자리에서
//       선언하는 것이 원칙이다. 수명이 짧을수록 실수가 줄어든다.
//     - n 을 미리 아니까 arr.reserve(n) 을 해주면 push_back 중에
//       일어나는 재할당(내부적인 realloc + 복사)이 사라진다.
//       reserve 는 공간만 잡고 size() 는 0 으로 둔다.
//       vector<int> arr(n) 과 다르다. 그건 0 으로 채운 n 칸을 만든다.
//     - sum 과 max 를 각각 도는데 한 루프로 합칠 수 있다.
//       지금 규모에선 성능 차이가 없고, 나눠 쓰는 쪽이 읽기 좋기도 하다.
//       의도한 것이면 그대로 둬도 된다.
//
// ============================================================
// [문제]
//   정수 개수 n 을 먼저 입력받고, 이어서 정수 n 개를 입력받아
//   합계와 최댓값을 출력하시오.
//
//   실행 예시 (첫 줄 5, 둘째 줄이 입력한 다섯 개)
//     How many numbers? 5
//     Enter numbers: 3 9 1 7 4
//     Sum: 24
//     Max: 9
//
//   출력 문구는 예시와 똑같지 않아도 된다. 형식은 마음대로.
//
//   조건
//     - 배열이나 malloc 사용 금지. std::vector 로 담을 것.
//     - 값은 push_back 으로 하나씩 넣을 것.
//     - 최댓값은 직접 구할 것. std::max_element 같은 기성 함수 금지.
//
//   컴파일
//     g++ -std=c++20 -Wall current.cpp -o /tmp/out && /tmp/out
// ============================================================

#include <iostream>
#include <vector>

int main() {
    int n;
    std::vector<int> arr;

    std::cin >> n;
    arr.reserve(n);

    while(n--) { // n을 건들이면 다음부터는 n이 아닌 arr.size()를 써야함.
        int input;
        std::cin >> input;
        arr.push_back(input);
    }

    int sum = 0;
    for(int x : arr) sum += x;

    int max = arr[0];
    for(int x : arr) if(max < x) max = x;

    std::cout
        << sum << "\n"
        << max << "\n";

    return 0;
}