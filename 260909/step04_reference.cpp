// [지난 스텝 통과 + 질문 답]
//
//   Step 3 통과. 출력 정확하다. 여러 줄에 걸친 << 정렬도 좋다.
//
//   질문 — "\n 은 std::endl 같은 건가? 뭘 더 추천하니"
//
//     둘 다 줄바꿈을 내보내지만 하는 일이 하나 다르다.
//
//       "\n"        줄바꿈 문자 하나를 버퍼에 넣는다.
//       std::endl   줄바꿈을 넣고, 추가로 버퍼를 즉시 비운다 (flush).
//
//     C 의 stdout 처럼 C++ 출력도 일단 버퍼에 모았다가 한꺼번에 내보낸다.
//     flush 는 "지금 당장 화면에 밀어내라"는 명령이고, 매번 하면 느리다.
//     반복문에서 수만 줄 찍을 때 endl 을 쓰면 체감될 만큼 느려진다.
//
//     추천: 평소엔 "\n" 을 쓴다.
//           endl 은 정말 지금 보여야 할 때만 (예: 프로그램이 곧 죽는 상황).
//           프로그램이 정상 종료되면 버퍼는 어차피 자동으로 비워지므로
//           마지막 줄에 endl 을 붙일 이유도 딱히 없다.
//
//     참고로 << " letters." << "\n" 은 << " letters.\n" 한 번으로 줄일 수 있다.
//
// ------------------------------------------------------------
//
// [개념] C 에 없던 것 — 참조(reference)
//
//   C 에서 함수가 바깥 변수를 바꾸려면 방법이 하나뿐이었다. 포인터다.
//
//     void add_one(int *p) { (*p)++; }   // 안에서는 * 로 풀고
//     add_one(&n);                       // 부를 때는 & 로 주소를 넘기고
//
//   C++ 에는 참조가 있다. 타입 뒤에 & 를 붙인다.
//
//     void add_one(int &r) { r++; }      // * 없음
//     add_one(n);                        // & 없음. 그냥 변수를 넘긴다
//
//   참조는 변수에 붙이는 "또 다른 이름"이다. 새 저장 공간이 아니라,
//   원래 변수 자체를 다른 이름으로 부르는 것이다. 그래서 r 을 바꾸면
//   n 이 바뀐다. 사실은 같은 놈이니까.
//
//   포인터와 뭐가 다른가:
//
//     포인터                          참조
//     ------------------------------  ------------------------------
//     NULL 일 수 있다                  절대 비어 있을 수 없다
//     나중에 다른 곳을 가리킬 수 있다   한 번 정해지면 평생 그 변수
//     선언만 하고 나중에 대입 가능      선언과 동시에 반드시 초기화
//     쓸 때 * 로 풀어야 한다            그냥 변수처럼 쓴다
//
//   즉 참조는 "널 검사가 필요 없고 실수할 여지가 적은 포인터"에 가깝다.
//   바꿔 말하면, 대상이 없을 수도 있는 상황에는 여전히 포인터를 쓴다.
//
// [문법]
//   int n = 10;
//   int &r = n;        // r 은 n 의 다른 이름. 선언과 동시에 초기화 필수.
//   r = 99;            // n 이 99 가 된다
//
//   void twice(int &x) { x = x * 2; }
//   twice(n);          // & 없이 호출. n 이 직접 바뀐다.
//
//   // 값을 바꾸지 않고 읽기만 할 거면 const 를 붙인다 (관용구)
//   void show(const std::string &s) { std::cout << s; }
//
// [힌트]
//   - 함수는 main 보다 위에 정의해야 그냥 쓸 수 있다.
//     (아래에 두려면 C 처럼 위쪽에 선언만 먼저 적어야 한다.)
//   - 값을 두 개 이상 바깥으로 내보내야 할 때 참조가 특히 편하다.
//     return 은 하나뿐이지만 참조 매개변수는 여러 개 둘 수 있다.
//   - 교환은 임시 변수 하나만 있으면 된다. C 에서 하던 그대로다.
//
// ============================================================
// [문제]
//   정수 두 개를 입력받아, 값을 서로 바꾸는 함수를 만들어 호출하시오.
//
//   실행 예시 (3 5 는 사용자가 입력한 값)
//     Enter two numbers: 3 5
//     Before: 3 5
//     After: 5 3
//
//   출력 문구는 예시와 똑같지 않아도 된다. 형식은 마음대로.
//   중요한 건 아래 조건이다.
//
//   조건
//     - 교환은 반드시 별도의 함수로 만들 것. main 안에서 직접 바꾸지 말 것.
//     - 그 함수는 포인터가 아니라 참조를 받을 것. 호출할 때 & 를 쓰지 말 것.
//     - std::swap 같은 기성 함수 사용 금지. 직접 구현할 것.
//
//   컴파일
//     g++ -std=c++20 -Wall current.cpp -o /tmp/out && /tmp/out
// ============================================================

#include <iostream>

void swap(int &a, int &b) {
    int tmp = a;
    a = b;
    b = tmp;
    return;
}

int main() {
    int a, b;
    std::cin >> a >> b;
    std::cout << a << b << std::endl;
    swap(a, b);
    std::cout << a << b << std::endl;

    return 0;
}