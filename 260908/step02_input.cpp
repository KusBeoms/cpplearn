// ============================================================
// Step 2 — 입력 받기
// ============================================================
//
// [개념] C의 scanf 자리에 C++은 std::cin 을 쓴다.
//
//   C                          C++
//   -------------------------  ---------------------------
//   #include <stdio.h>         #include <iostream>
//   scanf("%d", &n);           std::cin >> n;
//   %d 로 타입을 알려줘야 함    타입 안 알려줘도 됨
//   &n — 주소를 넘겨야 함       & 불필요
//
//   cin = character input, 즉 키보드.
//   >> 화살표가 cin 에서 변수 쪽으로 향한다. 데이터가 흘러가는 방향이다.
//   반대로 출력은 cout 쪽으로 << 가 향했다. 방향만 기억하면 된다.
//
//   scanf 는 %d 를 %f 로 잘못 쓰거나 & 를 빼먹으면 쓰레기값이 나오거나
//   프로그램이 터졌다. cin 은 변수 타입을 보고 알아서 읽으므로
//   그런 실수 자체가 생기지 않는다.
//
// [문법]
//   int n;
//   std::cin >> n;              // 정수 하나 읽기
//
//   int a, b;
//   std::cin >> a >> b;         // 공백이나 엔터로 구분해서 두 개 읽기
//
// [힌트]
//   - << 를 이어붙였던 것처럼 >> 도 이어붙일 수 있다.
//   - 안내 문구는 입력을 받기 "전에" 출력해야 화면에 먼저 보인다.
//   - 안내 문구 끝은 줄바꿈 없이 공백으로 두면 입력이 같은 줄에 이어진다.
//
// [지난 스텝 피드백]
//   - C++ 에서는 int main(void) 가 아니라 int main() 이라고 쓴다.
//     C 에서 (void) 는 "인자 없음"을 명시하는 용도였지만
//     C++ 에서는 빈 괄호가 이미 그 뜻이다.
//   - std::endl 과 "\n" 은 둘 다 줄바꿈이지만, endl 은 버퍼를 즉시
//     비운다(flush). 매번 flush 하면 느려서 실무에서는 "\n" 을 더 쓴다.
//
// ============================================================
// [문제]
//   정수 두 개를 입력받아 합을 출력하시오.
//
//   실행 예시 (3 5 는 사용자가 입력한 값)
//     Enter two numbers: 3 5
//     Sum: 8
//
//   조건
//     - scanf 사용 금지. std::cin 만 사용.
//     - "Enter two numbers: " 안내 문구도 출력할 것.
//
//   컴파일
//     g++ -std=c++20 -Wall current.cpp -o /tmp/out && /tmp/out
// ============================================================

#include <iostream>

int main(void) {
    int a, b;
    std::cout << "Enter two numbers : ";
    std::cin >> a >> b;
    std::cout << "Sum : " << a + b << std::endl;

    return 0;
}